"""Export utilities for lit-review-assistant.

Produces JSON, Markdown review, BibTeX scaffold, and CSV table.
"""

from __future__ import annotations

import csv
import io
import json
from pathlib import Path

from .models import LiteratureReview


def to_json(review: LiteratureReview, path: str | Path | None = None) -> str:
    out = json.dumps(review.to_dict(), indent=2)
    if path:
        Path(path).write_text(out, encoding="utf-8")
    return out


def to_markdown(review: LiteratureReview, path: str | Path | None = None) -> str:
    lines = []
    lines.append(f"# Literature Review: {review.topic}")
    lines.append("")
    lines.append(
        f"**{review.total_papers} papers** · "
        f"{review.year_range[0]}–{review.year_range[1]} · "
        + ", ".join(f"{v} ({n})" for v, n in sorted(review.venue_distribution.items(), key=lambda x: -x[1])[:5])
    )
    lines.append("")

    if review.synthesis:
        lines.append("## Synthesis")
        lines.append("")
        lines.append(review.synthesis)
        lines.append("")

    if review.research_gaps:
        lines.append("## Research Gaps")
        lines.append("")
        for g in review.research_gaps:
            lines.append(f"- {g}")
        lines.append("")

    if review.methodological_trends:
        lines.append("## Methodological Trends")
        lines.append("")
        for t in review.methodological_trends:
            lines.append(f"- {t}")
        lines.append("")

    if review.citation_scaffold:
        lines.append("## Citation Scaffold")
        lines.append("")
        lines.append("*Fill-in-the-blank paragraph for related work sections:*")
        lines.append("")
        lines.append(f"> {review.citation_scaffold}")
        lines.append("")

    lines.append("## Papers")
    lines.append("")
    for p in review.papers:
        rel_badge = {"high": "🟢", "medium": "🟡", "low": "🔴"}.get(p.relevance.value, "⚪")
        author_str = ", ".join(p.authors[:3]) + (" et al." if len(p.authors) > 3 else "")
        lines.append(f"### {rel_badge} {p.title}")
        lines.append("")
        lines.append(
            f"**{author_str}** · {p.venue} {p.year} · "
            f"`{p.paper_type.value}` · relevance: **{p.relevance.value}**"
        )
        if p.methodology:
            lines.append(f"*Methodology:* {p.methodology}")
        if p.llm_summary:
            lines.append("")
            lines.append(p.llm_summary)
        elif p.abstract:
            lines.append("")
            lines.append(p.abstract[:300] + ("…" if len(p.abstract) > 300 else ""))
        if p.key_contribution:
            lines.append("")
            lines.append(f"**Key contribution:** {p.key_contribution}")
        if p.limitations:
            lines.append(f"*Limitations:* {p.limitations}")
        if p.doi:
            lines.append(f"DOI: {p.doi}")
        if p.tags:
            lines.append(f"Tags: {', '.join(p.tags)}")
        lines.append("")

    enrichment_note = (
        f"*LLM-enriched via {review.llm_model}*" if review.llm_enriched else "*Rule-based output*"
    )
    lines.append("---")
    lines.append(f"*Generated by lit-review-assistant · CPR Orbital #40 · {enrichment_note}*")

    out = "\n".join(lines)
    if path:
        Path(path).write_text(out, encoding="utf-8")
    return out


def to_csv(review: LiteratureReview, path: str | Path | None = None) -> str:
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow([
        "citation_key", "title", "authors", "year", "venue",
        "paper_type", "relevance", "methodology", "key_contribution",
        "doi", "tags",
    ])
    for p in review.papers:
        writer.writerow([
            p.citation_key,
            p.title,
            "; ".join(p.authors),
            p.year,
            p.venue,
            p.paper_type.value,
            p.relevance.value,
            p.methodology,
            p.key_contribution,
            p.doi,
            ", ".join(p.tags),
        ])
    out = buf.getvalue()
    if path:
        Path(path).write_text(out, encoding="utf-8")
    return out


def to_bibtex_scaffold(review: LiteratureReview, path: str | Path | None = None) -> str:
    """Generate a BibTeX scaffold (filled from parsed data)."""
    lines = []
    for p in review.papers:
        btype = "inproceedings" if p.venue not in ("journal", "preprint") else "article"
        authors = " and ".join(p.authors) if p.authors else "Unknown"
        lines.append(f"@{btype}{{{p.citation_key},")
        lines.append(f"  title     = {{{p.title}}},")
        lines.append(f"  author    = {{{authors}}},")
        lines.append(f"  year      = {{{p.year}}},")
        lines.append(f"  booktitle = {{{p.venue}}},")
        if p.doi:
            lines.append(f"  doi       = {{{p.doi}}},")
        lines.append("}")
        lines.append("")
    out = "\n".join(lines)
    if path:
        Path(path).write_text(out, encoding="utf-8")
    return out
